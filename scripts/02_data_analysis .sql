-- Change Over Time Analysis
-- Analyzes how sales, revenue, orders, and other business metrics change over time (daily, monthly, or yearly)
-- to identify trends, growth, and declines.

-- 1. How has total sales revenue changed from year to year?
with total_sales_by_year as
(
select
extract('year' from order_date) as year_is,
sum(sales_amount) as total_revenue
from gold.sales
group by year_is
)

select
year_is,
total_revenue,
lag(total_revenue) over(order by year_is) as previous_year_revenue,
total_revenue - lag(total_revenue) over(order by year_is) as change_over_time
from total_sales_by_year

-- 2. Find the total sales revenue for each month and year.

select
	extract('year' from order_date) as year_is,
	to_char(order_date, 'FMMonth') as month_is,
	extract('month' from order_date) as month_number,
	sum(sales_amount) as total_sales
from gold.sales
group by year_is, month_is, month_number
order by year_is asc, month_number asc

-- 3. Compare each month's sales revenue with the previous month's revenue.

select
	extract('year' from order_date) as year_is,
	to_char(order_date, 'FMMonth') as month_is,
	extract('month' from order_date) as month_number,
	sum(sales_amount) as total_sales,
	lag(sum(sales_amount)) over(order by extract('year' from order_date), extract('month' from order_date))
	as previous_month_sales,
	sum(sales_amount) - lag(sum(sales_amount)) over(order by extract('year' from order_date), extract('month' from order_date))
	as sales_difference_from_previous_month
from gold.sales
group by year_is, month_is, month_number
order by year_is asc, month_number asc;

-- 4. Calculate the month-over-month percentage change in sales revenue.
with total_sales_table as
(
select
	extract('year' from order_date) as year_is,
	to_char(order_date, 'FMMonth') as month_is,
	extract('month' from order_date) as month_number,
	sum(sales_amount) as total_sales
from gold.sales
group by year_is, month_is, month_number
order by year_is asc, month_number asc
)

select
	*,
	lag(total_sales) over(order by year_is, month_is, month_number) as previous_month_sales,
	round((total_sales - lag(total_sales) over(order by year_is, month_is, month_number)) * 100.0 /
	nullif(lag(total_sales) over(order by year_is, month_is, month_number), 0), 2) as percentage_change
from total_sales_table

