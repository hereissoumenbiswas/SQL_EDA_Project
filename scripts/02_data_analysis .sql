-- 9. Compare each year's total revenue with the previous year's revenue and calculate the percentage change.
with totl_sales_by_year as
(
select
	extract('year' from order_date) as year_is,
	sum(sales_amount) as current_total_sales_amount,
	lag(sum(sales_amount)) over(order by extract('year' from order_date)) as previous_year_total_sales,
	sum(sales_amount) -lag(sum(sales_amount)) over(order by extract('year' from order_date)) as sales_changed
from gold.sales
group by year_is
order by year_is asc
)

select
*,
	round((current_total_sales_amount - previous_year_total_sales) * 100.0 /previous_year_total_sales, 2) as percentage_change
from totl_sales_by_year;

-- 10. Identify the month with the highest sales revenue in each year.
with sales_by_year as
(
select
	extract('year' from order_date) as year_is,
	extract('month' from order_date) as month_number,
	to_char(order_date, 'FMMonth') as month_name,
	sum(sales_amount) as total_sales_amount
from gold.sales
group by year_is, month_number, month_name
order by year_is, month_number
)

select
	*
from ( select
			*,
			dense_rank() over(partition by year_is order by month_number) as rank_is
		from sales_by_year
     ) as sub
where rank_is = 1;






















































































